#!/usr/bin/env python3
"""M9 — the widened grid's denominators: results/GRID9.md from cells9/.

usage: python3 gen/grid9_stats.py [--cells cells9] [--out results/GRID9.md]

Counts the generated cells and the skipped combinations per section and per
axis value, the expectations, and every skip reason with its count.
"""
import argparse, collections, json, os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", default="cells9")
    ap.add_argument("--out", default=os.path.join("results", "GRID9.md"))
    a = ap.parse_args()
    idx = [json.loads(l) for l in open(os.path.join(a.cells, "INDEX.jsonl"))]
    skipped = []
    for l in open(os.path.join(a.cells, "SKIPPED.txt")):
        if l.startswith("#") or not l.strip():
            continue
        head, reason = l.rstrip("\n").split(" -- ", 1)
        sec, t, p, o, ob = head.split(" ")
        skipped.append(dict(section=sec, T=t, P=p, O=o, observer=ob, reason=reason))
    L = ["# GRID9 — the widened grid's denominators (M9)", "",
         "Generated by `gen/grid9_stats.py` from `cells9/` (`gen/grid9.py`). Every combination the",
         "enumeration visits is either a cell or a skip with its reason; the two add up.", "",
         "| | cells | skipped | total |", "|---|---|---|---|",
         "| all | %d | %d | %d |" % (len(idx), len(skipped), len(idx) + len(skipped))]
    for sec in sorted(set(m["section"] for m in idx) | set(s["section"] for s in skipped)):
        g = sum(m["section"] == sec for m in idx)
        k = sum(s["section"] == sec for s in skipped)
        L.append("| section %s | %d | %d | %d |" % (sec, g, k, g + k))
    e = collections.Counter(m["expect"] for m in idx)
    L += ["", "Expectations: %s." % ", ".join("%s %d" % kv for kv in sorted(e.items()))]
    for axis in ("observer", "T", "P", "O"):
        vals = sorted(set(m[axis] for m in idx) | set(s[axis] for s in skipped))
        L += ["", "## By %s" % axis, "", "| %s | cells | REFUSE | SAFE | skipped |" % axis, "|---|---|---|---|---|"]
        for v in vals:
            gs = [m for m in idx if m[axis] == v]
            L.append("| %s | %d | %d | %d | %d |" % (v, len(gs), sum(m["expect"] == "REFUSE" for m in gs),
                                                    sum(m["expect"] == "SAFE" for m in gs),
                                                    sum(s[axis] == v for s in skipped)))
    r = collections.Counter(s["reason"] for s in skipped)
    L += ["", "## Skip reasons", "", "| combinations | reason |", "|---|---|"]
    L += ["| %d | %s |" % (v, k.replace("|", "\\|")) for k, v in r.most_common()]
    with open(a.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("%d cells, %d skipped -> %s" % (len(idx), len(skipped), a.out))


if __name__ == "__main__":
    main()
