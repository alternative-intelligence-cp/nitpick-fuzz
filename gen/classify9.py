#!/usr/bin/env python3
"""M9 — classify a widened-grid record (cells9.jsonl) and write SUMMARY9.md and
classified9.jsonl beside it.

usage: python3 gen/classify9.py results/<commit>/cells9.jsonl

Classes, in the order they are decided (classify.py's, extended):
  CRASH:npkc          npkc exited other than 0 or 1, or died by a signal, or timed out
  OVERRESTRICT        npkc refused a clone/read control the cell expects SAFE
  refused             npkc exited 1 (with its codes)
  timeout             a run leg hit the 10 s timeout
  other               a backend step failed after npkc 0, or an exit no rule names
  DEFECT:leg_mismatch the -O0 and -O2 exit codes differ
  clean               both legs exit the cell's expected code (0; 111 for a trap cell)
                      and, for the leak observer, live bytes after `run` equal the
                      cell's prediction on both legs
  DEFECT:uaf          70 (the free poison read) or 25 (the reuse sentinel read
                      through the original: freed and reused)
  DEFECT:double_free  95 (Unreachable: a free of what is not live)
  DEFECT:segv         107 (MachineFault) or 139 (SIGSEGV)
  DEFECT:leak         26 (a descriptor left open), or live bytes above the prediction
  DEFECT:wrong_value  20-29 otherwise (an observation's unexpected live value), 10,
                      live bytes BELOW the prediction (a double count), or a trap cell
                      that exited 0 (the failure it traps on became a success)
The leak reading: live = peak_live - 1048576, valid when allocated - 1048576 < 1048576.
A missing or unreadable heap line on a clean leak cell is `other`.
"""
import argparse, collections, json, os

PROBE = 1048576


def live_of(h):
    """-> (live, valid) from a heap triple, or (None, False)."""
    if not h:
        return None, False
    a, p, c = h
    return p - PROBE, (a - PROBE) < PROBE and p >= PROBE


def classify(r):
    rc = r["npkc"]
    if rc not in (0, 1):
        return "CRASH:npkc"
    if rc == 1:
        if r["O"] in ("clone", "read") and r["expect"] == "SAFE":
            return "OVERRESTRICT"
        return "refused"
    o0, o2 = r["O0"], r["O2"]
    if "T" in (o0, o2):
        return "timeout"
    if not isinstance(o0, int) or not isinstance(o2, int):
        return "other"
    if o0 != o2:
        return "DEFECT:leg_mismatch"
    c = o0
    want = r.get("expect_exit", 0) or 0
    if c == want:
        if r.get("observer") == "leak" and r.get("expect_live") is not None:
            for leg in ("O0", "O2"):
                live, ok = live_of(r.get("heap_" + leg))
                if live is None or not ok:
                    return "other"
                if live > r["expect_live"]:
                    return "DEFECT:leak"
                if live < r["expect_live"]:
                    return "DEFECT:wrong_value"
        return "clean"
    if want == 111 and c == 0:
        return "DEFECT:wrong_value"
    if c in (70, 25):
        return "DEFECT:uaf"
    if c == 95:
        return "DEFECT:double_free"
    if c in (107, 139):
        return "DEFECT:segv"
    if c == 26:
        return "DEFECT:leak"
    if 20 <= c <= 29 or c == 10:
        return "DEFECT:wrong_value"
    return "other"


def exp_mismatch(r):
    if r["expect"] == "REFUSE" and r["npkc"] == 0:
        return "accepted"
    if r["expect"] == "SAFE" and r["npkc"] == 1:
        return "refused"
    return ""


def codes_differ(r, metas):
    """A refusal whose codes do not include every code the rule names."""
    if r["npkc"] != 1 or r["expect"] != "REFUSE":
        return False
    want = metas.get(r["id"], {}).get("expect_codes") or []
    return bool(want) and not set(want) <= set(r["codes"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--cells", default="cells9")
    a = ap.parse_args()
    recs = [json.loads(l) for l in open(a.results) if l.strip()]
    recs.sort(key=lambda r: r["id"])
    metas = {}
    idx = os.path.join(a.cells, "INDEX.jsonl")
    if os.path.exists(idx):
        for l in open(idx):
            m = json.loads(l)
            metas[m["id"]] = m
    for r in recs:
        r["class"] = classify(r)
        r["exp_mismatch"] = exp_mismatch(r)
        r["codes_differ"] = codes_differ(r, metas)
        for leg in ("O0", "O2"):
            live, ok = live_of(r.get("heap_" + leg))
            r["live_" + leg] = live if ok else None
    outdir = os.path.dirname(os.path.abspath(a.results))
    commit = os.path.basename(outdir)
    by = collections.Counter(r["class"] for r in recs)
    L = ["# SUMMARY9 — the widened grid at `%s`" % commit, "",
         "Generated by `gen/classify9.py` from `%s` (%d cells)." % (os.path.basename(a.results), len(recs)), "",
         "## Count per class", "", "| class | cells |", "|---|---|"]
    for k, v in sorted(by.items()):
        L.append("| %s | %d |" % (k, v))
    L += ["", "## Expectation vs verdict", "", "| expectation | npkc 0 | npkc 1 | other |", "|---|---|---|---|"]
    for e in ("REFUSE", "SAFE"):
        rs = [r for r in recs if r["expect"] == e]
        L.append("| %s | %d | %d | %d |" % (e, sum(r["npkc"] == 0 for r in rs),
                                          sum(r["npkc"] == 1 for r in rs),
                                          sum(r["npkc"] not in (0, 1) for r in rs)))
    for axis in ("section", "observer", "T", "P", "O"):
        vals = sorted(set(str(r.get(axis)) for r in recs))
        classes = sorted(by)
        L += ["", "## Per class per %s" % axis, "",
              "| %s | %s |" % (axis, " | ".join(classes)),
              "|---|%s" % ("---|" * len(classes))]
        for v in vals:
            c = collections.Counter(r["class"] for r in recs if str(r.get(axis)) == v)
            L.append("| %s | %s |" % (v, " | ".join(str(c.get(k, 0)) for k in classes)))
    codes = collections.Counter(",".join(r["codes"]) for r in recs if r["npkc"] == 1)
    L += ["", "## Refusal codes", "", "| codes | cells |", "|---|---|"]
    for k, v in codes.most_common():
        L.append("| %s | %d |" % (k or "(none)", v))
    interesting = [r for r in recs if r["class"].startswith(("DEFECT", "CRASH", "OVERRESTRICT"))
                   or r["class"] in ("other", "timeout")]
    L += ["", "## Every DEFECT, CRASH, OVERRESTRICT, timeout and other", "",
          "| cell | class | npkc | O0 | O2 | live O0/O2 | expect | codes |", "|---|---|---|---|---|---|---|---|"]
    for r in interesting:
        L.append("| `%s` | %s | %s | %s | %s | %s/%s | %s | %s |" % (
            r["id"], r["class"], r["npkc"], r["O0"], r["O2"], r.get("live_O0"), r.get("live_O2"),
            r["expect"], ",".join(r["codes"])))
    ref = [r for r in recs if r["exp_mismatch"] == "refused" and r["class"] != "OVERRESTRICT"]
    L += ["", "## SAFE expected but refused (not a control)", ""]
    L += ["- `%s` %s" % (r["id"], ",".join(r["codes"])) for r in ref] or ["(none)"]
    acc = [r for r in recs if r["exp_mismatch"] == "accepted"]
    L += ["", "## REFUSE expected but accepted, by class", ""]
    c = collections.Counter(r["class"] for r in acc)
    L += ["- %s: %d" % (k, v) for k, v in sorted(c.items())] or ["(none)"]
    cd = [r for r in recs if r["codes_differ"]]
    L += ["", "## Refused, but without every code the rule names (%d)" % len(cd), ""]
    cc = collections.Counter((",".join(metas.get(r["id"], {}).get("expect_codes") or []), ",".join(r["codes"]))
                             for r in cd)
    L += ["| expected | got | cells |", "|---|---|---|"] + \
         ["| %s | %s | %d |" % (k[0], k[1], v) for k, v in cc.most_common()] if cd else ["(none)"]
    hl = [r for r in recs if r.get("heap_O0") is not None and r.get("heap_O0") != r.get("heap_O2")]
    L += ["", "## Leak cells whose two legs print different heap lines (%d)" % len(hl), ""]
    L += ["- `%s` O0 %s, O2 %s" % (r["id"], r["heap_O0"], r["heap_O2"]) for r in hl[:60]] or ["(none)"]
    with open(os.path.join(outdir, "SUMMARY9.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    with open(os.path.join(outdir, "classified9.jsonl"), "w") as fh:
        for r in recs:
            fh.write(json.dumps({k: r.get(k) for k in ("id", "section", "class", "exp_mismatch", "codes_differ",
                                                       "npkc", "codes", "O0", "O2", "live_O0", "live_O2")}) + "\n")
    print("%d cells -> %s" % (len(recs), os.path.join(outdir, "SUMMARY9.md")))
    for k, v in sorted(by.items()):
        print("  %-20s %d" % (k, v))


if __name__ == "__main__":
    main()
