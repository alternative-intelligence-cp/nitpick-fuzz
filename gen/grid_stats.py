#!/usr/bin/env python3
"""Write results/GRID.md: the grid's denominators, generated and skipped, by axis value,
and the skip reasons with their counts. usage: python3 gen/grid_stats.py [--cells cells]"""
import argparse, collections, json, os, re

ap = argparse.ArgumentParser(); ap.add_argument("--cells", default="cells"); a = ap.parse_args()
gen = [json.loads(l) for l in open(os.path.join(a.cells, "INDEX.jsonl"))]
sk = []
for l in open(os.path.join(a.cells, "SKIPPED.txt")):
    if l.startswith("#"): continue
    head, reason = l.rstrip("\n").split(" -- ", 1)
    t, p, o, ob = head.split()
    sk.append({"T": t, "P": p, "O": o, "observer": ob, "reason": reason})
L = ["# GRID — the denominators", "",
     "Generated by `gen/grid_stats.py` from `gen/grid.py`'s output.", "",
     "| | cells |", "|---|---|",
     "| combinations (T × P × O × observer) | %d |" % (len(gen) + len(sk)),
     "| generated | %d |" % len(gen), "| skipped | %d |" % len(sk),
     "| generated, expectation REFUSE | %d |" % sum(g["expect"] == "REFUSE" for g in gen),
     "| generated, expectation SAFE | %d |" % sum(g["expect"] == "SAFE" for g in gen)]
for axis in ("T", "P", "O", "observer"):
    g = collections.Counter(x[axis] for x in gen); s = collections.Counter(x[axis] for x in sk)
    L += ["", "## By %s" % axis, "", "| %s | generated | skipped |" % axis, "|---|---|---|"]
    for v in sorted(set(g) | set(s), key=lambda v: (-(g[v] + s[v]), v)):
        L.append("| %s | %d | %d |" % (v, g[v], s[v]))
r = collections.Counter(x["reason"] for x in sk)
L += ["", "## Skip reasons", "", "| reason | combinations |", "|---|---|"]
for k, v in r.most_common():
    L.append("| %s | %d |" % (k.replace("|", "/"), v))
os.makedirs("results", exist_ok=True)
open("results/GRID.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[:12]))
