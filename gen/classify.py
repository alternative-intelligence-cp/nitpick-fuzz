#!/usr/bin/env python3
"""M2.5 — classify a results/<commit>/cells.jsonl and write SUMMARY.md beside it.

usage: python3 gen/classify.py results/<commit>/cells.jsonl [--cells cells]

Classes, in the order they are decided:
  CRASH:npkc          npkc exited other than 0 or 1, or died by a signal, or timed out
  OVERRESTRICT        npkc refused a `clone` or `read` control
  refused             npkc exited 1 (with its codes)
  timeout             a run leg hit the 10 s timeout
  other               a backend step (opt/llc/ld.lld) failed after npkc 0 -- look by hand
  DEFECT:leg_mismatch the -O0 and -O2 exit codes differ
  clean               both legs exit 0
  DEFECT:uaf          70 (the free poison read)
  DEFECT:double_free  95 (Unreachable: a free of what is not live)
  DEFECT:segv         107 (MachineFault) or 139 (SIGSEGV)
  DEFECT:wrong_value  20-29 (an observation's unexpected live value), or 10
  other               anything else -- look by hand
Each record also gets `exp_mismatch`: REFUSE expected but compiled, or SAFE
expected but refused.
"""
import argparse, collections, json, os, sys


def classify(r):
    rc = r["npkc"]
    if rc not in (0, 1):
        return "CRASH:npkc"
    if rc == 1:
        return "OVERRESTRICT" if r["O"] in ("clone", "read") else "refused"
    o0, o2 = r["O0"], r["O2"]
    if "T" in (o0, o2):
        return "timeout"
    if not isinstance(o0, int) or not isinstance(o2, int):
        return "other"
    if o0 != o2:
        return "DEFECT:leg_mismatch"
    c = o0
    if c == 0:
        return "clean"
    if c == 70:
        return "DEFECT:uaf"
    if c == 95:
        return "DEFECT:double_free"
    if c in (107, 139):
        return "DEFECT:segv"
    if 20 <= c <= 29 or c == 10:
        return "DEFECT:wrong_value"
    return "other"


def exp_mismatch(r):
    if r["expect"] == "REFUSE" and r["npkc"] == 0:
        return "accepted"
    if r["expect"] == "SAFE" and r["npkc"] == 1:
        return "refused"
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    a = ap.parse_args()
    recs = [json.loads(l) for l in open(a.results) if l.strip()]
    recs.sort(key=lambda r: r["id"])
    for r in recs:
        r["class"] = classify(r)
        r["exp_mismatch"] = exp_mismatch(r)
    commit = os.path.basename(os.path.dirname(os.path.abspath(a.results)))
    by = collections.Counter(r["class"] for r in recs)
    L = ["# SUMMARY — grid results at `%s`" % commit, "",
         "Generated by `gen/classify.py` from `cells.jsonl` (%d cells)." % len(recs), "",
         "## Count per class", "", "| class | cells |", "|---|---|"]
    for k, v in sorted(by.items()):
        L.append("| %s | %d |" % (k, v))
    L += ["", "## Expectation vs verdict", "", "| expectation | npkc 0 | npkc 1 | other |", "|---|---|---|---|"]
    for e in ("REFUSE", "SAFE"):
        rs = [r for r in recs if r["expect"] == e]
        L.append("| %s | %d | %d | %d |" % (e, sum(r["npkc"] == 0 for r in rs),
                                          sum(r["npkc"] == 1 for r in rs),
                                          sum(r["npkc"] not in (0, 1) for r in rs)))
    for axis in ("T", "P", "O", "observer"):
        vals = sorted(set(r[axis] for r in recs))
        classes = sorted(by)
        L += ["", "## Per class per %s" % axis, "",
              "| %s | %s |" % (axis, " | ".join(classes)),
              "|---|%s" % ("---|" * len(classes))]
        for v in vals:
            c = collections.Counter(r["class"] for r in recs if r[axis] == v)
            L.append("| %s | %s |" % (v, " | ".join(str(c.get(k, 0)) for k in classes)))
    codes = collections.Counter(",".join(r["codes"]) for r in recs if r["npkc"] == 1)
    L += ["", "## Refusal codes", "", "| codes | cells |", "|---|---|"]
    for k, v in codes.most_common():
        L.append("| %s | %d |" % (k or "(none)", v))
    interesting = [r for r in recs if r["class"].startswith(("DEFECT", "CRASH", "OVERRESTRICT"))
                   or r["class"] in ("other", "timeout")]
    L += ["", "## Every DEFECT, CRASH, OVERRESTRICT, timeout and other", "",
          "| cell | class | npkc | O0 | O2 | expect | codes |", "|---|---|---|---|---|---|---|"]
    for r in interesting:
        L.append("| `%s` | %s | %s | %s | %s | %s | %s |" % (r["id"], r["class"], r["npkc"], r["O0"],
                                                         r["O2"], r["expect"], ",".join(r["codes"])))
    acc = [r for r in recs if r["exp_mismatch"] == "accepted"]
    ref = [r for r in recs if r["exp_mismatch"] == "refused" and r["class"] != "OVERRESTRICT"]
    L += ["", "## SAFE expected but refused (not a control)", ""]
    L += ["- `%s` %s" % (r["id"], ",".join(r["codes"])) for r in ref] or ["(none)"]
    L += ["", "## REFUSE expected but accepted, by class", ""]
    c = collections.Counter(r["class"] for r in acc)
    L += ["- %s: %d" % (k, v) for k, v in sorted(c.items())] or ["(none)"]
    out = os.path.join(os.path.dirname(a.results), "SUMMARY.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    with open(os.path.join(os.path.dirname(a.results), "classified.jsonl"), "w") as fh:
        for r in recs:
            fh.write(json.dumps({k: r[k] for k in ("id", "class", "exp_mismatch", "npkc", "codes", "O0", "O2")}) + "\n")
    print("%d cells -> %s" % (len(recs), out))
    for k, v in sorted(by.items()):
        print("  %-20s %d" % (k, v))


if __name__ == "__main__":
    main()
