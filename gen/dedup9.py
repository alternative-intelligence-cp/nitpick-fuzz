#!/usr/bin/env python3
"""M9 — deduplicate the widened grid's anomalies against KNOWN_DEFECTS.md.

usage: python3 gen/dedup9.py results/<commit>/ [--fixed DEF-99 DEF-102 ...]

Reads cells9.jsonl and classified9.jsonl (run gen/classify9.py first) and
writes DEDUP9.md beside them: every DEFECT, CRASH, OVERRESTRICT, timeout and
other, mapped to the known defect whose SHAPE it is, or to `candidate`, and
the candidates grouped by shape (P, O, class, and the live bytes of a leak).

A known defect counts only while its fix is absent from the compiler: pass
`--fixed` for each fix the compiler carries (at HUNT2 9126350: DEF-99, DEF-102,
DEF-104, DEF-105, DEF-106 and the faces F-001, F-002). A cell of a fixed
defect's shape that is still anomalous is a candidate: the fix did not cover it.

The shapes are KNOWN_DEFECTS.md's, stated on the widened grid's axes:
  DEF-99   a fixed place x any move out of it (move, pass_out, and M9's
           move_part, swap, conditional and loop moves): its fix refuses
           "move(...) or the implicit move at pass, of the binding or any part"
  DEF-102  lent_param x a write (field_write, assign, at_*), and self_lent (a
           pointer-receiver call on a loan): its fix names "every write path --
           assignment into or to the place, @, $$i/$$m, pointer-receiver calls"
  F-001    a for binding over owning elements x a write: for_binding, and the
           for over a slice parameter (for_slice, for_list) -- DEF-102's face
  DEF-104  generic_param x pass_out and x at_*
  F-002    generic_param x move -- DEF-104's face
  DEF-105  imported_fixed_bare x anything; _same/_wider x clone/read
  DEF-106  a fixed place x a write into a part (field_write, assign) and M9's
           swap into it
"""
import argparse, collections, json, os

FIXED = ("fixed_scalar", "fixed_elem", "imported_fixed_typed", "imported_fixed_bare",
         "imported_fixed_same", "imported_fixed_wider")
WRITES = ("field_write", "assign", "at_overwrite", "at_free", "at_grow")
MOVES = ("move", "pass_out", "move_part", "swap", "cond_move_t", "cond_move_f", "loop_move", "loop_move_nr")

RULES = [
    ("DEF-99", lambda r: r["P"] in FIXED and r["O"] in MOVES, "a move out of fixed storage"),
    ("DEF-106", lambda r: r["P"] in FIXED and r["O"] in ("field_write", "assign", "swap"),
     "a write into a part of a fixed binding"),
    ("DEF-102", lambda r: (r["P"] == "lent_param" and r["O"] in WRITES) or r["P"] == "self_lent",
     "a write through a lent parameter (a pointer-receiver call included)"),
    ("F-001", lambda r: r["P"] in ("for_binding", "for_slice", "for_list") and r["O"] in WRITES,
     "a write through a for binding over owning elements (DEF-102's face)"),
    ("DEF-104", lambda r: r["P"] == "generic_param" and r["O"] in ("pass_out", "at_overwrite", "at_free", "at_grow"),
     "a lent T passed out, or its address taken, in a generic body"),
    ("F-002", lambda r: r["P"] == "generic_param" and r["O"] == "move",
     "move(x) of a lent T in a generic body (DEF-104's face)"),
    ("DEF-105", lambda r: r["P"] == "imported_fixed_bare"
     or (r["P"] in ("imported_fixed_same", "imported_fixed_wider") and r["O"] in ("clone", "read")),
     "an imported fixed table's row type resolved in the importer's scope"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--fixed", nargs="*", default=[])
    a = ap.parse_args()
    cells = {}
    for l in open(os.path.join(a.dir, "cells9.jsonl")):
        if l.strip():
            r = json.loads(l)
            cells[r["id"]] = r
    rows = []
    for l in open(os.path.join(a.dir, "classified9.jsonl")):
        c = json.loads(l)
        if not (c["class"].startswith(("DEFECT", "CRASH", "OVERRESTRICT")) or c["class"] in ("other", "timeout")):
            continue
        r = dict(cells[c["id"]], **c)
        known = [d for d, pred, _ in RULES if pred(r) and d not in a.fixed]
        rows.append((r, known[0] if known else "candidate"))
    commit = os.path.basename(os.path.normpath(a.dir))
    by = collections.Counter(k for _, k in rows)
    L = ["# DEDUP9 — the widened grid's anomalies at `%s` against KNOWN_DEFECTS.md" % commit, "",
         "Generated by `gen/dedup9.py`%s. %d anomalies." % (
             " with the fixes of %s counted as present" % ", ".join(a.fixed) if a.fixed else "", len(rows)),
         "", "| known defect | cells |", "|---|---|"]
    L += ["| %s | %d |" % (k, v) for k, v in sorted(by.items())]
    # the candidates, grouped by shape
    cand = [r for r, k in rows if k == "candidate"]
    shapes = collections.defaultdict(list)
    for r in cand:
        live = r.get("live_O0") if r["class"] in ("DEFECT:leak", "DEFECT:wrong_value") and r.get("live_O0") is not None else ""
        shapes[(r["P"], r["O"], r["class"], live)].append(r)
    L += ["", "## The candidates by shape (%d cells, %d shapes)" % (len(cand), len(shapes)), "",
          "| P | O | class | live | cells (T observer: -O0/-O2) |", "|---|---|---|---|---|"]
    for (p, o, cl, live), rs in sorted(shapes.items(), key=lambda kv: (-len(kv[1]), str(kv[0]))):
        cs = " ".join("`%s` %s %s: %s/%s" % (r["id"][:5], r["T"], r["observer"][:2], r["O0"], r["O2"]) for r in rs)
        L.append("| %s | %s | %s | %s | %s |" % (p, o, cl, live, cs))
    groups = collections.defaultdict(list)
    for r, k in rows:
        if k != "candidate":
            groups[(k, r["P"], r["O"])].append(r)
    L += ["", "## The known defects' cells", "",
          "| known defect | P | O | cells (T observer: -O0/-O2, or the refusal) |", "|---|---|---|---|"]
    for (k, p, o), rs in sorted(groups.items()):
        cs = " ".join("`%s` %s %s: %s" % (r["id"][:5], r["T"], r["observer"][:2],
                                         ",".join(r["codes"]) if r["npkc"] != 0 else "%s/%s" % (r["O0"], r["O2"]))
                      for r in rs)
        L.append("| %s | %s | %s | %s |" % (k, p, o, cs))
    with open(os.path.join(a.dir, "DEDUP9.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("%d anomalies -> %s" % (len(rows), os.path.join(a.dir, "DEDUP9.md")))
    for k, v in sorted(by.items()):
        print("  %-10s %d" % (k, v))
    print("  candidate shapes: %d" % len(shapes))


if __name__ == "__main__":
    main()
