#!/usr/bin/env python3
"""M8.5 — compare two compilers' grid results cell by cell.

usage: python3 gen/compare.py results/<old>/ results/<new>/

Reads cells.jsonl and classified.jsonl in both directories (run
gen/classify.py first) and writes MOVES.md in the new one. A cell MOVED when
its (npkc rc, codes, -O0, -O2) differ between the two.

PLAN.md 8.5's expected moves, stated on the grid's axes. Each names the cells
it covers and the outcome it expects at the new compiler:
  DEF-102  lent_param   x a write              -> refused, TYPE-085
  F-001    for_binding  x a write              -> refused, TYPE-085
  DEF-104  generic_param x pass_out, assign, at_overwrite, at_free
                                               -> refused, TYPE-047 or TYPE-085
  F-002    generic_param x move                -> refused, TYPE-047 or TYPE-085
  DEF-105  imported_fixed_bare/_same/_wider x clone/read -> clean (0 on both legs)
  DEF-106  a fixed place x field_write/assign, except the whole binding's
           assignment (fixed_scalar x assign, ASSIGN-002 both before and after)
                                               -> refused, TYPE-086
(`a write` is field_write, assign, at_overwrite, at_free, at_grow. REPORT.md
section 6's 50 "expected refused, ran clean" cells are all inside the DEF-102,
F-001 and DEF-104 rows.)

Every cell is then one of:
  expected        moved, and its new outcome is the one its rule expects
  expected-held   did not move, and already had the expected outcome
  MISSING         a rule covers it, and its new outcome is not the expected one
  UNEXPECTED      moved, and no rule covers it: investigate (8.5)
  unchanged       did not move, and no rule covers it
"""
import argparse, collections, json, os

WRITES = ("field_write", "assign", "at_overwrite", "at_free", "at_grow")
FIXED = ("fixed_scalar", "fixed_elem", "imported_fixed_typed", "imported_fixed_bare",
         "imported_fixed_same", "imported_fixed_wider")


def refused_with(*codes):
    want = ["NITPICK-" + c for c in codes]
    return lambda r: r["npkc"] == 1 and any(c in r["codes"] for c in want)


def clean(r):
    return r["npkc"] == 0 and r["O0"] == 0 and r["O2"] == 0


RULES = [
    ("DEF-102", lambda r: r["P"] == "lent_param" and r["O"] in WRITES,
     refused_with("TYPE-085"), "refused TYPE-085"),
    ("F-001", lambda r: r["P"] == "for_binding" and r["O"] in WRITES,
     refused_with("TYPE-085"), "refused TYPE-085"),
    ("DEF-104", lambda r: r["P"] == "generic_param"
     and r["O"] in ("pass_out", "assign", "at_overwrite", "at_free"),
     refused_with("TYPE-047", "TYPE-085"), "refused TYPE-047 or TYPE-085"),
    ("F-002", lambda r: r["P"] == "generic_param" and r["O"] == "move",
     refused_with("TYPE-047", "TYPE-085"), "refused TYPE-047 or TYPE-085"),
    ("DEF-105", lambda r: r["P"] in ("imported_fixed_bare", "imported_fixed_same",
                                     "imported_fixed_wider") and r["O"] in ("clone", "read"),
     clean, "clean"),
    ("DEF-106", lambda r: r["P"] in FIXED and r["O"] in ("field_write", "assign")
     and not (r["P"] == "fixed_scalar" and r["O"] == "assign"),
     refused_with("TYPE-086"), "refused TYPE-086"),
]


def load(d):
    cells = {}
    for l in open(os.path.join(d, "cells.jsonl")):
        if l.strip():
            r = json.loads(l)
            cells[r["id"]] = r
    for l in open(os.path.join(d, "classified.jsonl")):
        c = json.loads(l)
        cells[c["id"]]["class"] = c["class"]
    return cells


def key(r):
    return (r["npkc"], tuple(r["codes"]), r["O0"], r["O2"])


def verdict(r):
    if r["npkc"] != 0:
        return "npkc %s %s" % (r["npkc"], ",".join(c.replace("NITPICK-", "") for c in r["codes"]))
    return "%s/%s" % (r["O0"], r["O2"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("old")
    ap.add_argument("new")
    a = ap.parse_args()
    old, new = load(a.old), load(a.new)
    oc, nc = (os.path.basename(os.path.normpath(d)) for d in (a.old, a.new))
    if set(old) != set(new):
        raise SystemExit("the two runs hold different cells: %d only in %s, %d only in %s"
                         % (len(set(old) - set(new)), oc, len(set(new) - set(old)), nc))
    rows = []
    for cid in sorted(new):
        o, n = old[cid], new[cid]
        moved = key(o) != key(n)
        rule = next(((name, ok, want) for name, pred, ok, want in RULES if pred(n)), None)
        if rule:
            status = ("expected" if moved else "expected-held") if rule[1](n) else "MISSING"
        else:
            status = "UNEXPECTED" if moved else "unchanged"
        rows.append((cid, n, o, moved, rule[0] if rule else "", rule[2] if rule else "", status))
    by = collections.Counter(s for *_, s in rows)
    L = ["# MOVES — `%s` against `%s`, cell by cell" % (nc, oc), "",
         "Generated by `gen/compare.py`. A cell moved when its (npkc rc, codes, -O0, -O2) differ.",
         "%d cells, %d moved." % (len(rows), sum(r[3] for r in rows)), "",
         "| status | cells |", "|---|---|"]
    L += ["| %s | %d |" % (k, by[k]) for k in ("expected", "expected-held", "MISSING", "UNEXPECTED", "unchanged")]
    # the move table: (rule, P, O, old class -> new verdict)
    groups = collections.defaultdict(list)
    for cid, n, o, moved, rule, want, status in rows:
        if moved or status == "MISSING":
            groups[(status, rule or "-", n["P"], n["O"], o["class"], verdict(n))].append(cid)
    L += ["", "## Every moved cell, and every MISSING one", "",
          "| status | rule | P | O | %s class | %s verdict | cells |" % (oc, nc), "|---|---|---|---|---|---|---|"]
    order = {"UNEXPECTED": 0, "MISSING": 1, "expected": 2, "expected-held": 3}
    for (status, rule, p, o, ocl, nv), cids in sorted(groups.items(), key=lambda kv: (order.get(kv[0][0], 9), kv[0])):
        L.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            status, rule, p, o, ocl, nv, " ".join("`%s`" % c[:5] for c in cids)))
    # class transitions
    tr = collections.Counter((o["class"], n["class"]) for cid, n, o, moved, *_ in rows if moved)
    L += ["", "## Class transitions of the moved cells", "", "| %s | %s | cells |" % (oc, nc), "|---|---|---|"]
    L += ["| %s | %s | %d |" % (f, t, v) for (f, t), v in sorted(tr.items())]
    out = os.path.join(a.new, "MOVES.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("%d cells, %d moved -> %s" % (len(rows), sum(r[3] for r in rows), out))
    for k in ("expected", "expected-held", "MISSING", "UNEXPECTED", "unchanged"):
        print("  %-14s %d" % (k, by[k]))


if __name__ == "__main__":
    main()
