#!/usr/bin/env python3
"""M5.2 (a) — deduplicate a compiler's anomalies against KNOWN_DEFECTS.md.

usage: python3 gen/dedup.py results/<commit>/ [--fixed DEF-99 ...]

Reads cells.jsonl and classified.jsonl (run gen/classify.py first) and writes
DEDUP.md beside them: every DEFECT, CRASH, OVERRESTRICT, timeout and other,
mapped to the known defect whose SHAPE it is, or to `candidate`.

A known defect counts only while its fix is absent from the compiler: pass
`--fixed` for each defect whose fix the compiler carries (at HUNT 6fb85d3,
DEF-99). A cell of a fixed defect's shape that is still anomalous is a
candidate: the fix did not cover it.

The shapes are KNOWN_DEFECTS.md's, stated on the grid's axes:
  DEF-102  lent_param x a write (field_write, assign, at_*): its fix covers
           "every write path -- assignment into or to the place, @, ..."
  DEF-104  generic_param x pass_out (TYPE-047), and x at_* (`@x` of a lent T,
           TYPE-085) -- the two operations its fix names
  DEF-105  imported_fixed_bare x anything (case 1, TYPE-001); _same/_wider x
           clone/read (the table read through the importer's own row type)
  DEF-106  a fixed place (fixed_*, imported_fixed_*) x field_write/assign
  DEF-99   a fixed place x move/pass_out
"""
import argparse, collections, json, os

FIXED = ("fixed_scalar", "fixed_elem", "imported_fixed_typed", "imported_fixed_bare",
         "imported_fixed_same", "imported_fixed_wider")
WRITES = ("field_write", "assign", "at_overwrite", "at_free", "at_grow")

RULES = [
    ("DEF-99", lambda r: r["P"] in FIXED and r["O"] in ("move", "pass_out"),
     "a move out of fixed storage"),
    ("DEF-102", lambda r: r["P"] == "lent_param" and r["O"] in WRITES,
     "a write through a lent parameter"),
    ("DEF-104", lambda r: r["P"] == "generic_param" and r["O"] in ("pass_out", "at_overwrite", "at_free", "at_grow"),
     "a lent T passed out, or its address taken, in a generic body"),
    ("DEF-105", lambda r: r["P"] == "imported_fixed_bare"
     or (r["P"] in ("imported_fixed_same", "imported_fixed_wider") and r["O"] in ("clone", "read")),
     "an imported fixed table's row type resolved in the importer's scope"),
    ("DEF-106", lambda r: r["P"] in FIXED and r["O"] in ("field_write", "assign"),
     "a write into a part of a fixed binding"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--fixed", nargs="*", default=[])
    a = ap.parse_args()
    cells = {}
    for l in open(os.path.join(a.dir, "cells.jsonl")):
        if l.strip():
            r = json.loads(l)
            cells[r["id"]] = r
    rows = []
    for l in open(os.path.join(a.dir, "classified.jsonl")):
        c = json.loads(l)
        if not (c["class"].startswith(("DEFECT", "CRASH", "OVERRESTRICT")) or c["class"] in ("other", "timeout")):
            continue
        r = dict(cells[c["id"]], **c)
        known = [d for d, pred, _ in RULES if pred(r) and d not in a.fixed]
        rows.append((r, known[0] if known else "candidate"))
    commit = os.path.basename(os.path.normpath(a.dir))
    by = collections.Counter(k for _, k in rows)
    L = ["# DEDUP — the anomalies at `%s` against KNOWN_DEFECTS.md" % commit, "",
         "Generated by `gen/dedup.py`%s. %d anomalies." % (
             " with the fixes of %s counted as present" % ", ".join(a.fixed) if a.fixed else "", len(rows)),
         "", "| known defect | cells |", "|---|---|"]
    L += ["| %s | %d |" % (k, v) for k, v in sorted(by.items())]
    groups = collections.defaultdict(list)
    for r, k in rows:
        groups[(k, r["P"], r["O"])].append(r)
    L += ["", "| known defect | P | O | cells (T: -O0/-O2, or the refusal) |", "|---|---|---|---|"]
    for (k, p, o), rs in sorted(groups.items()):
        cs = " ".join("`%s` %s: %s" % (r["id"][:5], r["T"],
                                      ",".join(r["codes"]) if r["npkc"] != 0 else "%s/%s" % (r["O0"], r["O2"]))
                      for r in rs)
        L.append("| %s | %s | %s | %s |" % (k, p, o, cs))
    with open(os.path.join(a.dir, "DEDUP.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("%d anomalies -> %s" % (len(rows), os.path.join(a.dir, "DEDUP.md")))
    for k, v in sorted(by.items()):
        print("  %-10s %d" % (k, v))


if __name__ == "__main__":
    main()
