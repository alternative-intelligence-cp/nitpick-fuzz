#!/usr/bin/env python3
"""M13 — classify a grid13 record (cells13.jsonl) and write SUMMARY13.md and
classified13.jsonl beside it.

usage: python3 gen/classify13.py --cells cells13 results/<commit>/cells13.jsonl

Each cell's metadata comes from <cells>/INDEX.jsonl (as classify9 reads cells9's):
gen/run.py copies only `section`, `expect_exit` and `expect_live` into a record, so
`expect_codes`, `scope` and the rule come from the index. A missing index is an
error, not a fallback.

Classes, decided in this order (the M13 brief's §5):
  1. CRASH:npkc     npkc exited other than 0 or 1, died by a signal, or timed out.
  2. npkc refused (1):
       refused        the cell expects REFUSE; `exp_mismatch` is "codes" when a code
                      the rule names is missing, "" when every one is there;
       OVERRESTRICT   any cell that expects SAFE;
       REFUSED_TRAP   a cell that expects TRAP.
  3. npkc accepted (0): the run class. The expected exit is the arm for a TRAP
     cell and 0 otherwise. The first rule that matches decides:
       timeout             a leg hit the run timeout;
       LOUD                a backend step failed on a leg (`opt!`, `llc!`, `ld!`);
       DEFECT:fallthrough  99, the failsafe's (*) arm, on either leg;
       DEFECT:leg_mismatch the -O0 and -O2 exits differ;
       clean               both legs give the expected exit (before the fault
                           rules, so a TRAP 107 cell that gives 107 is clean);
       DEFECT:uaf          70, 25 or 170;
       DEFECT:double_free  95;
       DEFECT:segv         107 or 139;
       DEFECT:wrong_value  12, 13 or 14, 20-29, or a TRAP cell that exits 0;
       DEFECT:false_trap   any other TRAPS arm (91-94, 96-98, 106, 108-117) the
                           cell does not expect;
       other               anything else.
  4. A cell that expects REFUSE and is accepted is ACCEPTED:<run class>. None is
     folded into clean: ACCEPTED:clean ran to 0 with no symptom.
  5. A cell whose program contains `wild` carries scope "wild" (from the index):
     classified as above, reported apart as the check of DEF-251 (i).
"""
import argparse, collections, json, os, sys

TRAP_ARMS = set(range(91, 95)) | set(range(96, 99)) | {106} | set(range(108, 118))


def run_class(r, want):
    o0, o2 = r["O0"], r["O2"]
    if "T" in (o0, o2):
        return "timeout"
    if any(isinstance(x, str) and x.startswith(("opt!", "llc!", "ld!")) for x in (o0, o2)):
        return "LOUD"
    if 99 in (o0, o2):
        return "DEFECT:fallthrough"
    if o0 != o2:
        return "DEFECT:leg_mismatch"
    if o0 == want:
        return "clean"
    c = o0
    if not isinstance(c, int):
        return "other"
    if c in (70, 25, 170):
        return "DEFECT:uaf"
    if c == 95:
        return "DEFECT:double_free"
    if c in (107, 139):
        return "DEFECT:segv"
    if c in (12, 13, 14) or 20 <= c <= 29 or (r["expect"] == "TRAP" and c == 0):
        return "DEFECT:wrong_value"
    if c in TRAP_ARMS:
        return "DEFECT:false_trap"
    return "other"


def classify(r):
    rc = r["npkc"]
    if rc not in (0, 1):
        return "CRASH:npkc"
    e = r["expect"]
    if rc == 1:
        return {"REFUSE": "refused", "SAFE": "OVERRESTRICT", "TRAP": "REFUSED_TRAP"}[e]
    want = r.get("expect_exit") if e == "TRAP" else 0
    c = run_class(r, want)
    return "ACCEPTED:" + c if e == "REFUSE" else c


def exp_mismatch(r, meta):
    if r["npkc"] == 1:
        if r["expect"] == "REFUSE":
            return "" if set(meta.get("expect_codes") or []) <= set(r["codes"]) else "codes"
        return "refused"
    if r["npkc"] == 0 and r["expect"] == "REFUSE":
        return "accepted"
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--cells", default="cells13")
    a = ap.parse_args()
    idx = os.path.join(a.cells, "INDEX.jsonl")
    if not os.path.exists(idx):
        sys.exit("classify13: %s is missing; generate the grid first (python3 gen/grid13.py)" % idx)
    metas = {}
    for l in open(idx):
        m = json.loads(l)
        metas[m["id"]] = m
    recs = [json.loads(l) for l in open(a.results) if l.strip()]
    recs.sort(key=lambda r: r["id"])
    missing = [r["id"] for r in recs if r["id"] not in metas]
    if missing:
        sys.exit("classify13: %d records have no cell in %s, the first %s" % (len(missing), idx, missing[0]))
    for r in recs:
        m = metas[r["id"]]
        r["class"] = classify(r)
        r["exp_mismatch"] = exp_mismatch(r, m)
        r["scope"] = m.get("scope", "plain")
        r["expect_codes"] = m.get("expect_codes") or []
    outdir = os.path.dirname(os.path.abspath(a.results))
    commit = os.path.basename(outdir)
    by = collections.Counter(r["class"] for r in recs)
    L = ["# SUMMARY13 — grid13 at `%s`" % commit, "",
         "Generated by `gen/classify13.py` from `%s` (%d cells; the metadata from `%s`)."
         % (os.path.basename(a.results), len(recs), idx), "",
         "## Count per class", "", "| class | cells |", "|---|---|"]
    for k, v in sorted(by.items()):
        L.append("| %s | %d |" % (k, v))
    L.append("| **generated** | **%d** |" % len(recs))
    L += ["", "## Expectation vs verdict", "", "| expectation | npkc 0 | npkc 1 | other |", "|---|---|---|---|"]
    for e in ("REFUSE", "SAFE", "TRAP"):
        rs = [r for r in recs if r["expect"] == e]
        L.append("| %s | %d | %d | %d |" % (e, sum(r["npkc"] == 0 for r in rs), sum(r["npkc"] == 1 for r in rs),
                                          sum(r["npkc"] not in (0, 1) for r in rs)))
    classes = sorted(by)
    for axis in ("section", "scope", "T", "P", "O"):
        vals = sorted(set(str(r.get(axis)) for r in recs))
        L += ["", "## Per class per %s" % axis, "", "| %s | %s |" % (axis, " | ".join(classes)),
              "|---|%s" % ("---|" * len(classes))]
        for v in vals:
            c = collections.Counter(r["class"] for r in recs if str(r.get(axis)) == v)
            L.append("| %s | %s |" % (v, " | ".join(str(c.get(k, 0)) for k in classes)))
    codes = collections.Counter(",".join(r["codes"]) for r in recs if r["npkc"] == 1)
    L += ["", "## Refusal codes", "", "| codes | cells |", "|---|---|"]
    for k, v in codes.most_common():
        L.append("| %s | %d |" % (k or "(none)", v))
    cm = [r for r in recs if r["exp_mismatch"] == "codes"]
    L += ["", "## Refused, but without every code the rule names (%d)" % len(cm), ""]
    if cm:
        cc = collections.Counter((",".join(r["expect_codes"]), ",".join(r["codes"])) for r in cm)
        L += ["| expected | got | cells |", "|---|---|---|"] + ["| %s | %s | %d |" % (k[0], k[1], v)
                                                              for k, v in cc.most_common()]
    else:
        L.append("(none)")
    look = [r for r in recs if r["class"] not in ("refused", "clean")]
    for scope, title in (("plain", "Every cell to triage (not `refused`, not `clean`), scope plain"),
                         ("wild", "Scope wild: the check of DEF-251 (i), reported apart")):
        rs = [r for r in look if r["scope"] == scope]
        L += ["", "## %s (%d)" % (title, len(rs)), ""]
        if rs:
            L += ["| cell | class | npkc | codes | O0 | O2 | expect |", "|---|---|---|---|---|---|---|"]
            for r in rs:
                L.append("| `%s` | %s | %s | %s | %s | %s | %s%s |" % (
                    r["id"], r["class"], r["npkc"], ",".join(r["codes"]) or "-", r["O0"], r["O2"], r["expect"],
                    (" " + str(r.get("expect_exit"))) if r["expect"] == "TRAP" else ""))
        else:
            L.append("(none)")
    with open(os.path.join(outdir, "SUMMARY13.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    with open(os.path.join(outdir, "classified13.jsonl"), "w") as fh:
        for r in recs:
            fh.write(json.dumps({k: r.get(k) for k in ("id", "section", "T", "P", "O", "observer", "scope", "expect",
                                                       "expect_exit", "class", "exp_mismatch", "npkc", "codes",
                                                       "O0", "O2")}) + "\n")
    print("%d cells -> %s" % (len(recs), os.path.join(outdir, "SUMMARY13.md")))
    for k, v in sorted(by.items()):
        print("  %-28s %d" % (k, v))


if __name__ == "__main__":
    main()
